/**
 * Decodes the golden frames generated by the Go server (protocol/fixtures), as
 * apple/RAKit/Tests/RAKitTests/FixtureTests.swift and web/src/protocol/fixtures.test.ts do.
 * Notifications go through RpcClient's own dispatcher.
 */
class FixtureTests {
    private fun notification(name: String): ServerMessage {
        val client = RpcClient("token")
        client.dispatch(fixture(name))
        return assertNotNull(client.messages.tryReceive().getOrNull(), "no message from $name")
    }

    private inline fun <reified R> result(name: String): R =
        WireCoding.json.decodeFromJsonElement(WireCoding.json.parseToJsonElement(fixture(name)).jsonObject.getValue("result"))

    @Test
    fun sessionEvents() {
        val n = assertIs<ServerMessage.Events>(notification("notification_events_session.json"))
        val events = n.events
        assertEquals(14, events.size)
        val session = assertNotNull(events[0].session)
        assertEquals(SessionStatus.AWAITING_APPROVAL, session.status)
        assertEquals(Workspace.Kind.WORKTREE, session.workspace.kind)
        assertEquals(0.0123, events[1].turn?.usage?.costUsd)
        val items = events.mapNotNull { it.item }
        assertEquals(11, items.size)
        assertEquals(
            listOf(
                ItemKind.USER_MESSAGE, ItemKind.REASONING, ItemKind.TOOL_CALL, ItemKind.ASSISTANT_MESSAGE, ItemKind.APPROVAL,
                ItemKind.APPROVAL, ItemKind.APPROVAL, ItemKind.PLAN, ItemKind.NOTICE, ItemKind.ERROR, ItemKind.ASSISTANT_MESSAGE,
            ),
            items.map { it.kind },
        )
        assertEquals("image/png", items[0].images?.first()?.mimeType)
        assertEquals(1170.0 / 2532.0, items[0].images?.first()?.aspectRatio)
        assertNull(items[2].images?.first()?.width) // WebP: no dimensions
        assertNull(items[2].images?.first()?.aspectRatio)
        assertEquals("go test ./...", items[2].tool?.input?.get("command")?.stringValue)
        assertEquals(0, items[2].tool?.exitCode)
        // A reply links to the images it shows as rad-image:<id>.
        val shown = assertNotNull(items[3].images?.first())
        assertTrue(items[3].text!!.endsWith("![Screenshot](rad-image:${shown.id})"))
        assertEquals(shown.id, ImageRef.idLinkedBy("rad-image:${shown.id}"))
        assertNull(ImageRef.idLinkedBy("https://example.com/a.png"))
        assertEquals(listOf(OptionKind.ALLOW_ONCE, OptionKind.ALLOW_SESSION, OptionKind.DENY), items[4].approval?.options?.map { it.kind })
        assertEquals(Approval.Special.QUESTION, items[5].approval?.special)
        assertEquals("SQLite", items[5].approval?.decision?.answers?.get("Which DB?"))
        assertEquals(Approval.Special.PLAN, items[6].approval?.special)
        assertEquals(2, items[7].plan?.entries?.size)
        assertEquals("i3", items[10].parentItemId)
        // Unknown event types decode without payload instead of failing the batch.
        assertEquals("future.event", events.last().type)
    }

    @Test
    fun indexEvents() {
        val events = assertIs<ServerMessage.Events>(notification("notification_events_index.json")).events
        assertEquals(listOf("project.upserted", "session.upserted", "project.removed"), events.map { it.type })
        assertEquals(true, events[0].project?.isGitRepo)
        assertEquals("p0", events[2].id)
    }

    @Serializable
    private data class Harnesses(val harnesses: List<HarnessInfo>)

    @Test
    fun responses() {
        val h = result<Harnesses>("response_harness_list.json").harnesses
        assertEquals(2, h.size)
        assertTrue(h[0].usable)
        assertTrue(!h[1].usable)
        assertTrue(!h[1].hint.isNullOrEmpty())
        // A model's own efforts replace the harness's; others get the default model's.
        val claude = h[0]
        assertEquals(listOf("low", "high"), claude.efforts(forModel = "sonnet").map { it.id })
        assertEquals(listOf("low", "medium", "high"), claude.efforts(forModel = null).map { it.id })
        assertTrue(h[1].efforts(forModel = null).isEmpty())
        assertEquals(listOf("/compact"), claude.commands?.map { it.prompt })
        assertTrue(!claude.commands?.first()?.description.isNullOrEmpty())
        assertNull(h[1].commands)

        val d = result<Diff>("response_diff.json")
        assertEquals(listOf(FileStat.Status.MODIFIED, FileStat.Status.RENAMED, FileStat.Status.ADDED), d.files.map { it.status })
        assertEquals(true, d.files[2].binary)

        assertEquals(2, result<FSListing>("response_fs_list.json").entries.size)

        val error = WireCoding.json.parseToJsonElement(fixture("response_error.json")).jsonObject.getValue("error")
        assertEquals("conflict", error.get("code")?.stringValue)

        val s = result<Session>("response_session.json")
        assertEquals("Fix the tests", s.title)
        assertEquals(0.26, s.context?.fraction)
        assertEquals("Sonnet 5.5", s.modelName(null))
        assertEquals("high", s.modelInfo?.effort)
        assertEquals("high", s.effort)

        val p = WireCoding.json.decodeFromString(PairResult.serializer(), fixture("http_pair_response.json"))
        assertEquals("0123abcd", p.token)

        val info = result<ServerInfo>("response_server_info.json")
        assertEquals(true, info.terminal)
        assertEquals("dev1", info.deviceId)
    }

    @Test
    fun notifications() {
        assertEquals(ServerMessage.Synchronized("session:s1", 14, true), notification("notification_synchronized.json"))
        assertEquals(ServerMessage.Resync("session:s1"), notification("notification_resync.json"))
        assertEquals(SubscribeResult("session:s1", 14), result<SubscribeResult>("response_subscribe.json"))
    }

    private fun terminal(name: String) = WireCoding.json.decodeFromString(TerminalMessage.serializer(), fixture(name))

    @Test
    fun terminalMessages() {
        val a = terminal("terminal_attached.json")
        assertTrue(a.type == "attached" && a.reset == true && a.offset == 262130L && a.cols == 80 && a.rows == 24 && !a.id.isNullOrEmpty())
        val r = terminal("terminal_resize.json")
        assertEquals(TerminalMessage(type = "resize", cols = 120, rows = 40), r)
        // What a client sends encodes as the server's fixture does.
        val sent = WireCoding.json.encodeToString(TerminalMessage.serializer(), TerminalMessage(type = "resize", cols = 120, rows = 40))
        assertEquals(WireCoding.json.parseToJsonElement(fixture("terminal_resize.json")), WireCoding.json.parseToJsonElement(sent))
        assertEquals(129, terminal("terminal_exit.json").exitCode)
        val e = terminal("terminal_error.json")
        assertTrue(e.code == "gone" && !e.message.isNullOrEmpty())
    }

    @Test
    fun terminalQuery() {
        assertEquals("session=s1&cols=80&rows=24&create=1", TerminalSession.query("s1", 80, 24, true, null, 0))
        assertEquals("session=s1&cols=100&rows=30&id=ab&offset=4096", TerminalSession.query("s1", 100, 30, false, "ab", 4096))
    }

    @Test
    fun goDates() {
        assertEquals(Instant.parse("2026-10-09T01:50:59.955123456Z"), WireCoding.parseDate("2026-10-09T01:50:59.955123456Z"))
        assertEquals(Instant.parse("2026-10-09T01:50:59Z"), WireCoding.parseDate("2026-10-09T01:50:59Z"))
        assertEquals(Instant.parse("2026-10-08T23:50:59.900Z"), WireCoding.parseDate("2026-10-09T01:50:59.9+02:00"))
        assertNull(WireCoding.parseDate("yesterday"))
    }

    @Test
    fun unknownValuesDecode() {
        // Newer servers may send kinds this app doesn't know.
        val json = """{"id":"i","sessionId":"s","order":1,"kind":"hologram","status":"teleporting","createdAt":"2026-10-09T01:50:59Z",""" +
            """"updatedAt":"2026-10-09T01:50:59Z","tool":{"name":"x","kind":"warp"},"extra":{"a":1}}"""
        val item = WireCoding.json.decodeFromString(dev.remoteagent.core.protocol.Item.serializer(), json)
        assertEquals(ItemKind.UNKNOWN, item.kind)
        assertEquals(dev.remoteagent.core.protocol.ItemStatus.UNKNOWN, item.status)
        assertEquals(dev.remoteagent.core.protocol.ToolKind.OTHER, item.tool?.kind)
    }

}
